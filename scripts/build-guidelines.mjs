// Turns ai/guidelines.md into supabase/functions/_shared/guidelines.ts, which the Edge Functions import.
// Run: npm run guidelines
// Rules: each "## " heading below maps to one AI feature. Lines starting with ">" are notes for humans and are
// skipped, as are "###" sub-headings and the "(add yours here)" placeholders.
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';

const SECTIONS = {
  'For every AI feature': 'general',
  'Itinerary planning': 'itinerary',
  'Outfit suggestions for each day': 'outfits',
  'Weather alerts': 'weather',
  'Spotting the type of a piece from its photo': 'categorise',
  'Outfit combinations from your wardrobe': 'combos',
  'Local picks when adding an entry': 'local',
  'Destination guides': 'destinations',
  'Describing a piece from its photo': 'describe',
  'Forecast-based outfit refresh': 'forecast',
};

const lines = readFileSync('ai/guidelines.md', 'utf8').split(/\r?\n/);
const out = Object.fromEntries(Object.values(SECTIONS).map((k) => [k, []]));
const unknown = [];
let current = null;

for (const raw of lines) {
  const line = raw.trimEnd();
  const heading = line.match(/^## (.+)$/);
  if (heading) {
    current = SECTIONS[heading[1].trim()] ?? null;
    if (!current) unknown.push(heading[1].trim());
    continue;
  }
  if (!current) continue;
  if (line.startsWith('>') || line.startsWith('###')) continue;
  if (line.includes('(add yours here)')) continue;
  if (line.trim() === '') continue;
  out[current].push(line);
}

const guidelines = Object.fromEntries(Object.entries(out).map(([k, v]) => [k, v.join('\n')]));

mkdirSync('supabase/functions/_shared', { recursive: true });
writeFileSync(
  'supabase/functions/_shared/guidelines.ts',
  `// GENERATED by scripts/build-guidelines.mjs from ai/guidelines.md. Edit that file, then run: npm run guidelines\n` +
    `export const GUIDELINES: Record<string, string> = ${JSON.stringify(guidelines, null, 2)};\n`,
);

for (const [key, text] of Object.entries(guidelines)) {
  console.log(`${key.padEnd(11)} ${text ? text.split('\n').length : 0} lines`);
}
if (unknown.length) console.warn(`\nHeadings I don't recognise (ignored): ${unknown.join('; ')}`);
